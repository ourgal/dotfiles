"""Organize a download folder by file format.

Safe by default: nothing is moved unless --apply is given. Every applied run
is logged inside the project, so --undo can roll back the last run.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import stat as stat_mod
import sys
from collections import defaultdict
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from rich.console import Console
from rich.markup import escape
from rich.table import Table

# Category -> lowercase extensions (no dot). Unknown extensions fall back to OTHER.
CATEGORIES: dict[str, frozenset[str]] = {
    "Videos": frozenset(
        {"mp4", "mkv", "mov", "avi", "wmv", "flv", "webm", "m4v", "mpg", "mpeg", "ts", "ogv", "rmvb", "3gp"}
    ),
    "Audio": frozenset({"mp3", "flac", "wav", "aac", "m4a", "ogg", "opus", "wma", "ape", "dsf", "aiff"}),
    "Pictures": frozenset(
        {"jpg", "jpeg", "png", "gif", "webp", "bmp", "tiff", "tif", "svg", "heic", "heif", "ico", "psd", "raw", "cr2", "nef"}
    ),
    "Documents": frozenset(
        {"pdf", "doc", "docx", "xls", "xlsx", "ppt", "pptx", "txt", "md", "rtf", "odt", "ods", "odp", "csv", "tsv"}
    ),
    "Ebooks": frozenset({"epub", "mobi", "azw", "azw3", "fb2", "djvu", "cbz", "cbr"}),
    "Archives": frozenset({"zip", "rar", "7z", "tar", "gz", "bz2", "xz", "zst", "tgz", "cab"}),
    "Installers": frozenset({"exe", "msi", "msix", "appx", "dmg", "pkg", "apk", "deb", "rpm"}),
    "Extensions": frozenset({"crx", "xpi"}),
    "DiskImages": frozenset({"iso", "img", "vhd", "vhdx", "vmdk", "qcow2"}),
    "Code": frozenset(
        {
            "py", "ps1", "bat", "cmd", "sh", "js", "mjs", "cjs", "ts", "jsx", "tsx",
            "html", "htm", "css", "scss", "json", "yaml", "yml", "toml", "xml", "ini",
            "reg", "c", "h", "cpp", "hpp", "java", "go", "rs", "sql", "lua", "php", "leojs",
        }
    ),
    "Fonts": frozenset({"ttf", "otf", "woff", "woff2", "ttc"}),
    "Data": frozenset({"dat", "db", "sqlite", "sqlite3", "bin", "log"}),
}

OTHER = "Others"
# Files generated by the OS; skipped even when the hidden attribute is missing.
EXCLUDED_FILES = {"desktop.ini", "thumbs.db"}
STATE_DIRNAME = ".state"


@dataclass(frozen=True, slots=True)
class Move:
    src: Path
    dst: Path
    category: str


def find_project_root() -> Path | None:
    """Walk up from this file to the project root (the folder with pyproject.toml)."""
    for parent in Path(__file__).resolve().parents:
        if (parent / "pyproject.toml").is_file():
            return parent
    return None


def default_source() -> Path:
    """Default to the project's parent folder, which is Downloads."""
    root = find_project_root() or Path.cwd()
    return root.parent


def human_size(size: int) -> str:
    value = float(size)
    for unit in ("B", "KB", "MB", "GB"):
        if value < 1024:
            return f"{value:.0f} {unit}" if unit == "B" else f"{value:.1f} {unit}"
        value /= 1024
    return f"{value:.1f} TB"


def shorten(name: str, limit: int = 46) -> str:
    return name if len(name) <= limit else name[: limit - 3] + "..."


def is_hidden(path: Path) -> bool:
    if path.name.startswith("."):
        return True
    if os.name == "nt":
        try:
            attrs = path.stat().st_file_attributes  # type: ignore[attr-defined]
        except (OSError, AttributeError):
            return False
        flags = stat_mod.FILE_ATTRIBUTE_HIDDEN | stat_mod.FILE_ATTRIBUTE_SYSTEM
        return bool(attrs & flags)
    return False


def unique_dest(folder: Path, name: str, reserved: set[str]) -> Path:
    """Append (1), (2), ... when the target exists or is already taken by this plan."""
    candidate = folder / name
    if not candidate.exists() and candidate.name.casefold() not in reserved:
        return candidate
    stem, suffix = candidate.stem, candidate.suffix
    index = 1
    while True:
        candidate = folder / f"{stem} ({index}){suffix}"
        if not candidate.exists() and candidate.name.casefold() not in reserved:
            return candidate
        index += 1


def build_lookup() -> dict[str, str]:
    return {ext: category for category, exts in CATEGORIES.items() for ext in exts}


def plan_moves(source: Path, dest: Path, *, include_hidden: bool = False) -> list[Move]:
    lookup = build_lookup()
    moves: list[Move] = []
    reserved: set[str] = set()

    for entry in sorted(source.iterdir(), key=lambda p: p.name.casefold()):
        if not entry.is_file():
            continue
        if entry.name.casefold() in EXCLUDED_FILES:
            continue
        if not include_hidden and is_hidden(entry):
            continue

        ext = entry.suffix.lower().lstrip(".")
        category = lookup.get(ext, OTHER)
        dst = unique_dest(dest / category, entry.name, reserved)
        reserved.add(dst.name.casefold())
        moves.append(Move(entry, dst, category))

    return moves


def file_size(path: Path) -> int:
    try:
        return path.stat().st_size
    except OSError:
        return 0


def show_plan(moves: list[Move], source: Path, dest: Path, console: Console) -> None:
    groups: dict[str, list[Move]] = defaultdict(list)
    for move in moves:
        groups[move.category].append(move)

    table = Table(title="Plan", title_justify="left", title_style="bold")
    table.add_column("Category", style="cyan", no_wrap=True)
    table.add_column("Count", justify="right")
    table.add_column("Size", justify="right")
    table.add_column("Examples", overflow="fold")

    location = f"[bold]Source[/] {escape(str(source))}"
    if dest != source:
        location += f"\n[bold]Target[/] {escape(str(dest))}"
    console.print(location)

    ordered = sorted(groups, key=lambda c: (c == OTHER, -len(groups[c]), c))
    for category in ordered:
        items = groups[category]
        size = sum(file_size(m.src) for m in items)
        sample = "\n".join(shorten(m.src.name) for m in items[:3])
        if len(items) > 3:
            sample += f"\n... and {len(items) - 3} more"
        table.add_row(category, str(len(items)), human_size(size), escape(sample))

    table.add_section()
    total_size = sum(file_size(m.src) for m in moves)
    table.add_row("[bold]Total[/]", f"[bold]{len(moves)}[/]", f"[bold]{human_size(total_size)}[/]", "")

    console.print(table)


def apply_moves(moves: list[Move], project_dir: Path, console: Console, verbose: bool) -> tuple[list[Move], list[tuple[Move, str]]]:
    done: list[Move] = []
    failed: list[tuple[Move, str]] = []

    for move in moves:
        try:
            move.dst.parent.mkdir(parents=True, exist_ok=True)
            dst = move.dst
            if dst.exists():
                dst = unique_dest(dst.parent, dst.name, set())
            shutil.move(str(move.src), str(dst))
            done.append(Move(move.src, dst, move.category))
            if verbose:
                console.print(f"  [dim]{escape(move.src.name)}[/] -> [cyan]{escape(move.category)}/[/]")
        except OSError as exc:
            failed.append((move, str(exc)))

    if done:
        write_journal(project_dir, moves[0].src.parent, done)

    return done, failed


def write_journal(project_dir: Path, source: Path, moves: list[Move]) -> Path:
    runs = project_dir / STATE_DIRNAME / "runs"
    runs.mkdir(parents=True, exist_ok=True)
    path = runs / f"{datetime.now():%Y%m%d-%H%M%S-%f}.json"
    payload = {
        "created": datetime.now().isoformat(timespec="seconds"),
        "source": str(source),
        "moves": [{"src": str(m.src), "dst": str(m.dst), "category": m.category} for m in moves],
    }
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return path


def undo_last_run(project_dir: Path, console: Console, verbose: bool) -> int:
    runs = sorted((project_dir / STATE_DIRNAME / "runs").glob("*.json"))
    if not runs:
        console.print("[yellow]No undo log found.[/]")
        return 1

    path = runs[-1]
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        console.print(f"[red]Cannot read undo log: {escape(str(path))} ({exc})[/]")
        return 2

    remaining: list[dict[str, str]] = []
    restored = 0
    for item in reversed(data.get("moves", [])):
        src, dst = Path(item["src"]), Path(item["dst"])
        if not dst.exists():
            console.print(f"[yellow]Skipped[/] {escape(dst.name)}: no longer in its category folder")
            continue
        if src.exists():
            console.print(f"[yellow]Skipped[/] {escape(src.name)}: a file with that name already exists at the original location")
            remaining.append(item)
            continue
        try:
            src.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(dst), str(src))
            restored += 1
            if verbose:
                console.print(f"  [cyan]{escape(item['category'])}/[/] -> [dim]{escape(src.name)}[/]")
        except OSError as exc:
            console.print(f"[red]Failed[/] {escape(src.name)}: {exc}")
            remaining.append(item)

    if remaining:
        path.write_text(
            json.dumps({**data, "moves": list(reversed(remaining))}, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
        console.print(f"[yellow]Restored {restored} file(s); {len(remaining)} could not be restored, log kept.[/]")
    else:
        path.unlink()
        console.print(f"[green]Restored {restored} file(s); log cleared.[/]")

    return 0 if not remaining else 1


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="file-organizer",
        description="Organize a download folder by file format. Preview only unless --apply is given.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""Examples:
  uv run file-organizer                    preview the plan for Downloads
  uv run file-organizer --apply            move files
  uv run file-organizer -v --apply         move files and list each one
  uv run file-organizer --undo             roll back the last run
  uv run file-organizer -s "D:\\Downloads"  organize another folder
""",
    )
    parser.add_argument(
        "-s", "--source", type=Path, default=None,
        help="folder to organize (default: the project's parent folder, i.e. Downloads)",
    )
    parser.add_argument(
        "-d", "--dest", type=Path, default=None,
        help="where category folders are created (default: same as source)",
    )
    parser.add_argument("--apply", action="store_true", help="actually move files (default is preview only)")
    parser.add_argument("--undo", action="store_true", help="roll back the last --apply run")
    parser.add_argument("--include-hidden", action="store_true", help="include hidden files")
    parser.add_argument("-v", "--verbose", action="store_true", help="print every moved file")
    return parser


def main(argv: list[str] | None = None) -> int:
    console = Console()
    parser = build_parser()
    args = parser.parse_args(argv)

    project_dir = find_project_root() or Path.cwd()

    try:
        if args.undo:
            return undo_last_run(project_dir, console, args.verbose)

        source = (args.source or default_source()).resolve()
        if not source.is_dir():
            console.print(f"[red]Directory not found: {escape(str(source))}[/]")
            return 2

        dest = (args.dest or source).resolve()
        if dest.exists() and not dest.is_dir():
            console.print(f"[red]Destination is not a directory: {escape(str(dest))}[/]")
            return 2

        moves = plan_moves(source, dest, include_hidden=args.include_hidden)
        if not moves:
            console.print("[green]Nothing to organize.[/]")
            return 0

        show_plan(moves, source, dest, console)

        if not args.apply:
            console.print("\n[yellow]Preview only: no files were moved. Run with [bold]--apply[/bold] to move them.[/]")
            return 0

        console.print()
        done, failed = apply_moves(moves, project_dir, console, args.verbose)
        total = sum(file_size(m.dst) for m in done)

        if done:
            console.print(f"[green]Done: moved {len(done)} file(s), {human_size(total)}.[/]")
            console.print(f"[dim]Undo log: {escape(str(project_dir / STATE_DIRNAME / 'runs'))}[/]")
        for move, reason in failed:
            console.print(f"[red]Failed[/] {escape(move.src.name)}: {escape(reason)}")
        if failed:
            console.print(f"[yellow]{len(failed)} file(s) were not moved (they may be in use).[/]")
            return 1
        return 0

    except KeyboardInterrupt:
        console.print("\n[yellow]Cancelled.[/]")
        return 130
    except PermissionError as exc:
        console.print(f"[red]Permission denied: {escape(str(exc))}[/]")
        return 3


if __name__ == "__main__":
    sys.exit(main())
